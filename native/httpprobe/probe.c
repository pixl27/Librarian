/* Arm DR0 at base+0xa75a0b1 on the current thread (sync /sign parses on the
 * same thread that read the body). The VEH logs if it is reached. */
static void set_drs(CONTEXT *c)
{
    if (g_databp) {
        /* DR0 = data read/write breakpoint (RW0=11, LEN0=11 -> 8 bytes) on the body */
        c->Dr0 = (DWORD64)(ULONG_PTR)g_databp_addr;
        c->Dr7 = (c->Dr7 & ~(DWORD64)0xffffffff) | 0x1 | (0x3ULL << 16) | (0x3ULL << 18);
        return;
    }
    c->Dr0 = (DWORD64)(ULONG_PTR)g_bp_addr[0];
    c->Dr1 = (DWORD64)(ULONG_PTR)g_bp_addr[1];
    c->Dr2 = (DWORD64)(ULONG_PTR)g_bp_addr[2];
    c->Dr3 = (DWORD64)(ULONG_PTR)g_bp_addr[3];
    /* enable L0..L3 (bits 0,2,4,6 = 0x55); RW/LEN fields 0 = execute, len 1 */
    c->Dr7 = (c->Dr7 & ~(DWORD64)0xffffffff) | 0x55;
}
static void arm_all_threads(void)
{
    CONTEXT c; memset(&c, 0, sizeof c); c.ContextFlags = CONTEXT_DEBUG_REGISTERS;
    HANDLE th = GetCurrentThread();
    if (GetThreadContext(th, &c)) { set_drs(&c); c.ContextFlags = CONTEXT_DEBUG_REGISTERS; SetThreadContext(th, &c); }
    DWORD me = GetCurrentThreadId(), pid = GetCurrentProcessId(), armed = 0;
    HANDLE snap = CreateToolhelp32Snapshot(TH32CS_SNAPTHREAD, 0);
    if (snap != INVALID_HANDLE_VALUE) {
        THREADENTRY32 te; te.dwSize = sizeof te;
        if (Thread32First(snap, &te)) do {
            if (te.th32OwnerProcessID != pid || te.th32ThreadID == me) continue;
            HANDLE h = OpenThread(THREAD_SUSPEND_RESUME | THREAD_GET_CONTEXT | THREAD_SET_CONTEXT, FALSE, te.th32ThreadID);
            if (!h) continue;
            SuspendThread(h);
            CONTEXT tc; memset(&tc, 0, sizeof tc); tc.ContextFlags = CONTEXT_DEBUG_REGISTERS;
            if (GetThreadContext(h, &tc)) { set_drs(&tc); tc.ContextFlags = CONTEXT_DEBUG_REGISTERS; if (SetThreadContext(h, &tc)) armed++; }
            ResumeThread(h);
            CloseHandle(h);
        } while (Thread32Next(snap, &te));
        CloseHandle(snap);
    }
    probe_log("%s armed on current + %lu other threads", g_databp ? "DATABP" : "HWBP(4)", armed);
}
static void arm_hwbp(void)
{
    BYTE *base = (BYTE *)GetModuleHandleW(NULL);
    if (!base) return;
    for (int i = 0; i < 4; i++) g_bp_addr[i] = base + g_bp_rva[i];
    arm_all_threads();
}

/* Arm DR3 (execute) at the json extractor entry on the CURRENT thread only. */
static void arm_keycap_current(void)
{
    BYTE *base = (BYTE *)GetModuleHandleW(NULL);
    if (!base) return;
    g_keycap_addr = base + g_keycap_rva;
    CONTEXT c; memset(&c, 0, sizeof c); c.ContextFlags = CONTEXT_DEBUG_REGISTERS;
    HANDLE th = GetCurrentThread();
    if (!GetThreadContext(th, &c)) return;
    c.Dr3 = (DWORD64)(ULONG_PTR)g_keycap_addr;
    /* enable L3 (bit 6); RW3/LEN3 = 00 -> execute, 1 byte */
    c.Dr7 = (c.Dr7 & ~((DWORD64)0x3 << 6)) | ((DWORD64)0x1 << 6);
    c.Dr7 &= ~((DWORD64)0xff << 28);   /* RW3/LEN3 fields = 0 (execute) */
    c.ContextFlags = CONTEXT_DEBUG_REGISTERS;
    SetThreadContext(th, &c);
    probe_log("KEYCAP armed DR3 @%p (rva 0x%lx) tid=%lu", g_keycap_addr, g_keycap_rva, GetCurrentThreadId());
}

