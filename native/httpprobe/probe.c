/*
 * keycap: recover the /sign response schema from ground truth. The generic JSON
 * member extractor lives at rva 0xb4876b0 and takes the key in r8 (proven: the
 * consumer call site passes "rebe_token" in r8). The /sign parse is synchronous
 * on the thread that read the body, so we arm an exec breakpoint on the extractor
 * ENTRY on that one thread only (arming all threads would trap this hot function
 * process-wide) and log every key it searches for during the parse window. The
 * sequence of keys IS the schema.
 */
static int  g_keycap;                       /* ini: capture parser key lookups */
