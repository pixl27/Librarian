/*
 * WinHTTP probe / stub — instrumentation and controlled response injection.
 *
 * Two jobs, both read-only against Capcom unless explicitly told otherwise:
 *
 *  1. CAPTURE. Log the game's backend conversation — hosts, verbs, paths,
 *     status codes, and (for Capcom hosts, or all hosts under capture_all) the
 *     request and response bodies. This is how the auth exchange on
 *     mtm.rebe.capcom.com/v1/steam-steam/sign was read: a 401 with body
 *     {"error":{"code":269625600,"message":"Ticket decrypt error"}}.
 *
 *  2. STUB. Answer a configured request with a synthetic 200 + body without ever
 *     talking to Capcom, to learn whether the game will proceed past the auth
 *     gate at all. If a faked /sign lets it reach PlayFab / Party init, the only
 *     thing between here and private-server co-op is a transport shim, not a
 *     cryptographic wall. If Denuvo re-checks the token and the game stalls
 *     anyway, even that route is closed. The capture then shows exactly what it
 *     tried next.
 *
 * Everything in (2) is off unless librarian_http.ini beside this DLL turns it
 * on, so an ordinary launch is a pure pass-through. The genuine System32 library
 * must sit beside this one as winhttp_o.dll.
 */

